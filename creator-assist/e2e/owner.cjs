// End-to-end check of the demo owner account against a local Supabase (see README → Testing).
// Run: pnpm build && pnpm start, then `node e2e/owner.cjs`. Resets nothing; run after `supabase db reset`.
const { chromium } = require("playwright");
const SHOTS = __dirname + "/.shots/";
require("fs").mkdirSync(SHOTS, { recursive: true });
const BASE = "http://localhost:3000";
let failures = 0;
// Seed dates are relative to today (IST), so expected labels are too.
const day = (offset) => { const d = new Date(Date.now() + 5.5 * 3600e3 + offset * 864e5); return d.getUTCDate() + " " + d.toLocaleString("en-IN", { month: "short", timeZone: "UTC" }); };
// Reminders: 9:00 am, 5:00 pm on the due date, 1:00 am the next day (every 8 hours); legal notice due 9:00 am that day.
const DUE = day(-18), DUE1 = day(-17);
const ok = (cond, msg) => { console.log((cond ? "  ✓ " : "  ✗ ") + msg); if (!cond) failures++; };

(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, acceptDownloads: true });
  const page = await ctx.newPage();
  page.on("pageerror", (e) => { console.log("  PAGE ERROR", e.message); failures++; });
  const text = async () => (await page.locator("main").innerText()).replace(/\s+/g, " ");
  const shot = (n) => page.screenshot({ path: SHOTS + n + ".png", fullPage: true });

  console.log("Sign in as owner");
  await page.goto(BASE + "/signin");
  await shot("01-signin");
  await page.getByLabel("Mobile number").fill("98765 43210");
  await page.getByRole("button", { name: "Send OTP" }).click();
  await page.getByLabel("Enter OTP").fill("482913");
  await page.getByRole("button", { name: "Verify and continue" }).click();
  await page.waitForURL("**/home", { timeout: 30000 });
  await page.waitForSelector("text=Money owed to you");
  let t = await text();
  ok(t.includes("Hi, Ravi"), "greets owner by env name");
  ok(t.includes("₹85,300"), "money owed ₹85,300");
  ok(t.includes("3 open invoices · ₹38,100 overdue"), "3 open invoices · ₹38,100 overdue");
  ok(t.includes("₹47,200"), "due this week ₹47,200");
  ok(t.includes("₹8,500"), "TDS to be deducted ₹8,500");
  ok(t.includes("Overdue 18 days") && t.includes("Reminder sent") && t.includes("Due in 4 days") && t.includes("Awaiting sign"), "needs-attention chips match prototype");
  ok(t.includes(`Balance after ₹15,000 advance · due ${DUE}`), "Voltra sub line");
  await shot("02-home");

  console.log("Deals filters");
  await page.getByRole("link", { name: "Deals", exact: true }).click();
  await page.waitForURL("**/deals");
  t = await text();
  for (const c of ["All · 5", "Overdue · 1", "Awaiting pay · 2", "To sign · 1", "Paid · 1"]) ok(t.includes(c), "chip " + c);
  await page.getByRole("link", { name: "Overdue · 1" }).click();
  await page.waitForURL("**/deals?f=over");
  ok((await page.locator("a.item").count()) === 1, "Overdue filter shows 1 deal");
  await shot("03-deals-overdue");
  await page.getByRole("link", { name: "Paid · 1" }).click();
  await page.waitForURL("**/deals?f=paid");
  t = await text();
  ok(t.includes("Zenvolt") && t.includes("₹29,500") && !t.includes("Voltra Motors"), "Paid filter shows Zenvolt ₹29,500");

  console.log("Voltra deal detail");
  await page.goto(BASE + "/deals");
  await page.getByRole("link", { name: /Voltra Motors/ }).click();
  await page.waitForSelector("text=Timeline");
  t = await text();
  ok(t.includes("Balance overdue 18 days"), "chip Balance overdue 18 days");
  ok(t.includes("₹33,600"), "balance to receive ₹33,600");
  ok(t.includes("MSME interest so far: ₹310 on the ₹38,100 unpaid, for 18 days."), "MSME interest ₹310");
  ok(t.includes("2 Reels · 3 Stories") && t.includes("3 months · included"), "deal facts");
  ok(t.includes(`3 reminders sent, read by brand · ${DUE}–${DUE1}`) && t.includes(`Legal notice due · ${DUE1}`), "timeline reminders then legal notice due");
  ok(t.includes("Time for the legal notice") && t.includes("3 reminders sent and Voltra Motors still hasn't paid"), "deal prompts the legal notice after 3 reminders");
  await shot("04-deal");
  const dealUrl = page.url();

  console.log("Invoice");
  await page.getByRole("link", { name: "Invoice" }).click();
  await page.waitForSelector("text=Taxable value");
  t = await text();
  ok(t.includes("RTK/2026-27/014"), "invoice number");
  ok(t.includes("Instagram Reel × 2 · SAC 998361 ₹36,000") && t.includes("Instagram Story × 3 · SAC 998361 ₹9,000"), "line split 36,000 / 9,000");
  ok(t.includes("IGST 18% ₹8,100") && t.includes("₹53,100") && t.includes("Rupees fifty-three thousand one hundred only"), "IGST + total + words");
  ok(t.includes("₹38,100") && t.includes("A/c ending 4417"), "balance + bank");
  await shot("05-invoice");
  const pdf = await page.request.get(BASE + (await page.getByRole("link", { name: "Download PDF" }).getAttribute("href")));
  ok(pdf.status() === 200 && pdf.headers()["content-type"] === "application/pdf" && (await pdf.body()).length > 5000, "invoice PDF downloads");
  require("fs").writeFileSync(SHOTS + "invoice.pdf", await pdf.body());
  await page.getByRole("button", { name: "Send again" }).click();
  await page.waitForSelector(".toast.on");
  ok((await page.locator(".toast").innerText()).includes("Sample deal"), "send again on sample is suppressed: " + (await page.locator(".toast").innerText()));

  console.log("Reminders");
  await page.goto(dealUrl + "/reminders");
  await page.waitForSelector(".bubble");
  t = await text();
  ok(t.includes(`Friendly · ${DUE}, 9:00 am`) && t.includes(`Follow-up · ${DUE}, 5:00 pm`) && t.includes(`Final notice · ${DUE1}, 1:00 am`) && t.includes("Sent · read"), "3 reminders, 8 hours apart");
  ok(t.includes(`Legal notice · ${DUE1}, 9:00 am`) && t.includes("Due now") && !!(await page.getByRole("link", { name: "Send legal notice" }).count()), "legal notice step after the reminders");
  let bubble = await page.locator(".bubble").innerText();
  ok(bubble.startsWith(`Hi Arjun, hope you are well. The balance of ₹38,100 on invoice RTK/2026-27/014 was due on ${DUE} and is now 18 days overdue.`), "English message");
  ok(bubble.includes("MSME-registered"), "MSME line on");
  await page.getByRole("radio", { name: "Telugu-Eng" }).click();
  bubble = await page.locator(".bubble").innerText();
  ok(bubble.includes("Arjun garu") && bubble.includes("18 days overdue ayyindi"), "Telugu-English rewrite");
  await page.getByRole("radio", { name: "Hinglish" }).click();
  bubble = await page.locator(".bubble").innerText();
  ok(bubble.includes("18 din overdue hai"), "Hinglish rewrite");
  const wa = await page.getByRole("link", { name: "Send now on WhatsApp" }).getAttribute("href");
  ok(wa.startsWith("https://wa.me/919000012345?text=") && decodeURIComponent(wa).includes("din overdue"), "wa.me link prefilled in chosen language");
  await shot("06-reminders");

  console.log("Escalate + lawyer notice");
  await page.goto(dealUrl + "/escalate");
  t = await text();
  ok(t.includes("₹310") && t.includes("16.5% a year (3 × RBI bank rate)"), "escalate interest card");
  await shot("07-escalate");
  ok(t.includes("1 · Send final reminder") && t.includes("2 · Send legal notice") && !t.includes("1,499"), "escalate options, no fee");
  await page.getByRole("link", { name: /Send legal notice/ }).click();
  await page.waitForURL("**/notice");
  await page.waitForSelector(".paper");
  t = await text();
  for (const k of [
    "RTK/2026-27/014", "within 7 days", "Authorised Representative for RAVI TEJA K",
    "Principal amount outstanding under Tax Invoice No. RTK/2026-27/014: ₹38,100",
    "Interest @ 10% per week", "(18 days): ₹9,797", "Legal fee towards this notice: ₹5,000", "Total payable as on", "₹52,897",
    "lodge a complaint against you",
  ]) ok(t.includes(k), "notice preview: " + k);
  const noticeRes = await page.request.get(dealUrl.replace("/deals/", "/api/deals/") + "/notice");
  const buf = await noticeRes.body();
  ok(noticeRes.ok() && noticeRes.headers()["content-type"] === "application/pdf" && buf.subarray(0, 4).toString() === "%PDF", "notice PDF renders");
  require("fs").writeFileSync(SHOTS + "notice.pdf", buf);
  await shot("08-notice");
  const noticeWa = page.locator("a", { hasText: "Send via WhatsApp" });
  const waHref = await noticeWa.getAttribute("href");
  ok(waHref === null, "WhatsApp disabled until facts confirmed");
  await page.getByLabel("I confirm the facts in this notice are correct").check();
  const href = await noticeWa.getAttribute("href");
  ok(href?.startsWith("https://wa.me/") && decodeURIComponent(href).includes("/api/n/"), "WhatsApp message links the notice PDF");
  const publicLink = decodeURIComponent(href).match(/https?:\/\/\S+\/api\/n\/\S+/)[0].replace(/^https?:\/\/[^/]+/, BASE);
  const anon = await browser.newContext();
  ok((await anon.request.get(publicLink)).status() === 404, "public notice link closed before sending");
  await page.getByRole("button", { name: /Send via email/ }).click();
  await page.waitForSelector("text=notice emailed to you");
  ok(true, "sample notice emailed to the creator");
  const pub = await anon.request.get(publicLink);
  ok(pub.ok() && (await pub.body()).subarray(0, 4).toString() === "%PDF", "public notice link opens after sending");
  ok((await anon.request.get(publicLink.slice(0, -3) + "xyz")).status() === 404, "tampered notice link rejected");
  await anon.close();
  await page.goto(dealUrl);
  ok((await text()).includes("Legal notice sent by email"), "timeline shows notice sent");

  console.log("After the notice: wait, then legal team call");
  await page.goto(dealUrl + "/escalate");
  t = await text();
  ok(t.includes("Legal notice sent") && t.includes("₹52,897") && t.includes("What happens next"), "escalate shows notice sent and total claimed");
  ok(t.includes("1 · Wait for the notice period") && t.includes("7 days left"), "notice period countdown");
  ok(t.includes("2 · Talk to the legal team") && t.includes("₹599 · 15 min") && !t.includes("Send final reminder"), "legal call option at ₹599");
  await shot("08b-after-notice");
  await page.getByRole("link", { name: /Talk to the legal team/ }).click();
  await page.waitForURL("**/legal-call");
  ok((await text()).includes("15-minute call with Sri Hari Legal Chambers"), "legal call page");
  await page.getByLabel("Call me on").fill("98765 43210");
  await page.getByLabel(/Share this deal/).check();
  await page.getByRole("button", { name: "Pay ₹599 and book call" }).click();
  await page.waitForURL("**/legal-call/booked**");
  t = await text();
  ok(t.includes("Call booked") && t.includes("Beta: no payment was taken"), "legal call booked with beta note");
  await page.goto(dealUrl + "/escalate");
  ok((await text()).includes("Call booked ·"), "escalate shows the booked call");
  await shot("08-notice-sent");

  console.log("Record payment");
  await page.goto(dealUrl + "/payment");
  ok((await page.getByLabel("Amount received in bank (₹)").inputValue()) === "33600", "amount prefilled 33600");
  ok((await page.getByLabel("TDS deducted by brand (₹)").inputValue()) === "4500", "TDS prefilled 4500");
  ok((await text()).includes("₹0 · fully settled"), "live balance settled");
  await shot("09-payment");
  await page.getByRole("button", { name: "Save payment" }).click();
  await page.waitForURL("**/paid**");
  ok((await text()).includes("Voltra Motors is marked paid. Pending reminders were cancelled and ₹4,500 TDS was added to your Tax hub."), "paid confirmation copy");
  await page.goto(dealUrl + "/reminders");
  t = await text();
  ok(!t.includes("Due now") && !(await page.getByRole("link", { name: "Send legal notice" }).count()), "no legal-notice prompt once paid");

  console.log("Tax hub");
  await page.goto(BASE + "/tax");
  t = await text();
  ok(t.includes("₹1,10,000") && t.includes("4 brands"), "income invoiced ₹1,10,000 · 4 brands");
  ok(t.includes("₹19,800"), "GST collected ₹19,800");
  ok(t.includes("₹11,000"), "TDS by brands ₹11,000");
  ok(t.includes("₹5,300") && t.includes("₹5,700 missing"), "AIS ₹5,300 / ₹5,700 missing");
  ok(t.includes("Voltra Motors TDS ₹4,500 not in AIS") && t.includes("FitFuel Foods TDS ₹1,200 not in AIS"), "mismatch rows");
  ok(t.includes("GSTR-1 · October") && t.includes("GSTR-3B · October") && t.includes("Income tax return"), "coming up filings");
  await shot("10-tax");
  await page.locator("a", { hasText: "Remind" }).first().click();
  await page.waitForSelector(".bubble");
  bubble = await page.locator(".bubble").innerText();
  ok(bubble.includes("is not showing in my AIS (PAN ABCDE1234F)"), "TDS reminder message");
  await shot("11-tds-remind");
  await page.getByRole("button", { name: "Send by email only" }).click();
  await page.waitForSelector(".toast.on");
  console.log("    toast:", await page.locator(".toast").innerText());
  await page.reload();
  ok((await text()).includes("Follow-up ·"), "TDS ladder scheduled");

  console.log("Who files + filing beta + AI call");
  await page.goto(BASE + "/tax");
  await page.getByRole("radio", { name: "My own CA" }).click();
  await page.waitForTimeout(800);
  await page.reload();
  ok((await page.getByRole("radio", { name: "My own CA" }).getAttribute("aria-checked")) === "true", "filer toggle persists");
  await page.getByRole("button", { name: "Send ITR data to my CA" }).click();
  await page.waitForSelector(".toast.on");
  ok((await page.locator(".toast").innerText()).includes("Beta"), "ITR send shows beta note");
  await page.getByRole("radio", { name: "Creator Assist" }).click();
  await page.goto(BASE + "/tax/file");
  await page.getByLabel("I consent to sharing my tax data with the filing CA").check();
  await page.getByRole("button", { name: /book call/ }).click();
  await page.waitForURL("**/booked**");
  ok((await text()).includes("Beta: no call is actually scheduled"), "AI call booked + beta note");
  await shot("12-booked");

  console.log("Brand signing page (Urban Roots, sample)");
  await page.goto(BASE + "/deals?f=sign");
  await page.locator("a.item").first().click();
  await page.waitForSelector("text=Copy signing link");
  const signLink = await page.getByRole("link", { name: "Preview what the brand sees" }).getAttribute("href");
  await shot("13-agreement");
  const brand = await browser.newContext({ viewport: { width: 375, height: 812 } });
  const bp = await brand.newPage();
  await bp.goto(signLink);
  let bt = (await bp.locator("main").innerText()).replace(/\s+/g, " ");
  ok(bt.includes("Ravi Teja K sent you an agreement") && bt.includes("Urban Roots Cafe"), "public page loads without login");
  ok((await bp.locator("nav.nav").count()) === 0 && (await bp.locator(".fab").count()) === 0, "no tab bar / feedback on brand page");
  await bp.getByLabel("Your name").fill("Sameer Rao");
  await bp.getByLabel("Designation").fill("Owner");
  await bp.getByRole("button", { name: "Send OTP to email" }).click();
  await bp.waitForSelector("p[role=status]");
  const code = (await bp.locator("p[role=status]").innerText()).match(/(\d{6})/)[1];
  await bp.getByLabel("Email OTP").fill("000000");
  await bp.getByLabel(/I accept on behalf of/).check();
  await bp.getByRole("button", { name: "Accept and sign" }).click();
  await bp.waitForSelector("text=That code doesn't match");
  ok(true, "wrong OTP rejected");
  await bp.getByLabel("Email OTP").fill(code);
  await bp.getByRole("button", { name: "Accept and sign" }).click();
  await bp.waitForSelector("text=Agreement signed", { timeout: 20000 });
  await bp.screenshot({ path: SHOTS + "14-signed.png", fullPage: true });
  const bpdf = await bp.request.get(await bp.getByRole("link", { name: "Download PDF copy" }).evaluate((a) => a.href));
  ok(bpdf.status() === 200 && bpdf.headers()["content-type"] === "application/pdf", "brand can download signed PDF");
  require("fs").writeFileSync(SHOTS + "agreement.pdf", await bpdf.body());
  await page.reload();
  ok((await text()).includes("Signed by Sameer Rao, Owner"), "creator sees signature");

  console.log("Feedback + admin");
  await page.goto(BASE + "/brands");
  t = await text();
  ok(t.includes("Slow payer") || t.includes("Paid late"), "brands show payment behaviour");
  await shot("15-brands");
  await page.getByRole("button", { name: "Feedback" }).click();
  await page.getByLabel("Your feedback").fill("E2E: the brands list is great");
  await page.getByRole("button", { name: "Send feedback" }).click();
  await page.waitForSelector("text=Thanks! Feedback sent.");
  await page.goto(BASE + "/admin/feedback");
  ok((await text()).includes("E2E: the brands list is great") && (await text()).includes("/brands"), "feedback reaches /admin/feedback");

  console.log("Admin dashboard");
  await page.goto(BASE + "/settings");
  await page.getByRole("link", { name: "Admin dashboard" }).click();
  await page.waitForURL("**/admin");
  t = await text();
  ok(t.includes("Legal notices") && t.includes("Legal calls to confirm") && t.includes("Tester feedback"), "dashboard tiles and tabs");
  ok(t.includes("Voltra Motors") && t.includes("RTK/2026-27/014") && t.includes("Paid") && t.includes("Pay-by date"), "notice listed with status (paid after recording payment)");
  const adminPdf = await page.request.get(dealUrl.replace("/deals/", "/api/admin/notice/"));
  ok(adminPdf.ok() && (await adminPdf.body()).subarray(0, 4).toString() === "%PDF", "admin can open any notice PDF");
  await page.getByRole("link", { name: "Legal calls" }).click();
  await page.waitForURL("**tab=calls");
  t = await text();
  ok(t.includes("+919876543210") || t.includes("98765 43210"), "legal call booking listed with phone");
  await page.getByRole("radio", { name: "Confirmed" }).click();
  await page.waitForSelector("text=Marked confirmed");
  await page.reload();
  ok((await page.getByRole("radio", { name: "Confirmed" }).getAttribute("aria-checked")) === "true", "legal call confirmed and saved");
  await page.getByRole("link", { name: "Tax filings" }).click();
  await page.waitForURL("**tab=tax");
  ok((await text()).includes("GSTR-1") || (await text()).includes("No filings handled"), "tax filings tab");
  await shot("15b-admin");

  console.log("Appearance");
  await page.goto(BASE + "/settings");
  await page.getByRole("radio", { name: "Light" }).click();
  ok((await page.evaluate(() => document.documentElement.dataset.theme)) === "light", "light theme applied at once");
  await page.reload();
  ok((await page.evaluate(() => document.documentElement.dataset.theme)) === "light", "light theme kept after reload (server-rendered)");
  await page.getByRole("radio", { name: "Dark" }).click();
  ok((await page.evaluate(() => getComputedStyle(document.querySelector(".phone")).backgroundColor)) === "rgb(17, 17, 17)", "dark theme tokens");
  await page.getByRole("radio", { name: "System" }).click();
  ok((await page.evaluate(() => document.documentElement.dataset.theme)) === undefined, "system clears the override");

  console.log("Settings: export, clear + reload sample");
  await page.goto(BASE + "/settings");
  t = await text();
  ok(t.includes("ABCDE••••F") && t.includes("HDFC ••4417") && t.includes("RTK"), "masked PAN/bank");
  await shot("16-settings");
  const exp = await page.request.get(BASE + "/api/export");
  const data = await exp.json();
  ok(data.profile.pan === "ABCDE1234F" && data.deals.length === 5 && !("pan_enc" in data.profile && data.profile.pan_enc), "export has decrypted data, 5 deals");
  await page.getByRole("button", { name: "Clear sample data" }).click();
  await page.waitForSelector("text=Sample data cleared");
  await page.goto(BASE + "/home");
  t = await text();
  ok(t.includes("No deals yet") && t.includes("Try with sample data"), "empty dashboard after clear");
  await page.getByRole("button", { name: "Try with sample data" }).click();
  await page.waitForSelector("text=Money owed to you");
  ok((await text()).includes("₹85,300"), "sample reloaded, same numbers");
  await page.goto(BASE + "/home");
  // double-load attempt via server action is idempotent: check deal count stays 5
  await page.goto(BASE + "/deals");
  ok((await text()).includes("All · 5"), "no duplicates after reload");

  await browser.close();
  console.log(failures ? `\n${failures} FAILURE(S)` : "\nALL OWNER CHECKS PASSED");
  process.exit(failures ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
